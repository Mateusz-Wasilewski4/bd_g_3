SELECT AVG(pensja) AS srednia_pensja FROM EMPLOYEE;
SELECT AVG(pensja) AS srednia_pensja, COUNT(*) AS liczba_pracownikow FROM EMPLOYEE GROUP BY JOB_POSITION_ID;
SELECT AVG(YEAR(CURRENT_DATE()) - YEAR(BIRTH_DATE)) AS sredni_wiek , DEPARTMENT_ID FROM EMPLOYEE GROUP BY DEPARTMENT_ID;

#ZAD2
SELECT SUM(pensja) AS suma_pensji, DEPARTMENT_ID FROM EMPLOYEE GROUP BY DEPARTMENT_ID ORDER BY suma_pensji DESC;

SELECT JOB_POSITION_ID, AVG(pensja) AS srednia_pensja
FROM EMPLOYEE
GROUP BY JOB_POSITION_ID
HAVING COUNT(*) >= 3 AND srednia_pensja > 3000;

SELECT DEPARTMENT_ID, COUNT(DISTINCT pensja) AS rozne_pensje
FROM EMPLOYEE
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) > 4
ORDER BY rozne_pensje ASC;


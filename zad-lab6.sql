CREATE TABLE DEPARTMENT AS SELECT * FROM company_2025.DEPARTMENT;
CREATE TABLE JOB_POSITION AS SELECT * FROM company_2025.JOB_POSITION;

SELECT DEPARTMENT.DEPARTMENT_NAME AS nazwa_departamentu, COUNT(EMPLOYEE.EMPLOYEE_NAME) AS liczba_pracownikow
FROM DEPARTMENT 
LEFT JOIN EMPLOYEE
ON EMPLOYEE.DEPARTMENT_ID = DEPARTMENT.DEPARTMENT_ID
GROUP BY DEPARTMENT.DEPARTMENT_ID, DEPARTMENT.DEPARTMENT_NAME;

SELECT DEPARTMENT.DEPARTMENT_NAME AS NAZWA_DEPARTAMENTU,
CONCAT(EMPLOYEE.FIRST_NAME, ' ',EMPLOYEE.LAST_NAME) AS PRACOWNIK
FROM DEPARTMENT
JOIN EMPLOYEE
ON EMPLOYEE.DEPARTMENT_ID = DEPARTMENT.DEPARTMENT_ID;


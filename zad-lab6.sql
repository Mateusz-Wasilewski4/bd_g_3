SELECT LAST_NAME, POSITION_NAME FROM EMPLOYEE
NATURAL JOIN JOB_POSITION
WHERE BIRTH_DATE >= '1990-01-01' AND BIRTH_DATE < '2000-01-01';

SELECT FIRST_NAME AS imie, LAST_NAME AS nazwisko
FROM EMPLOYEE
NATURAL JOIN JOB_POSITION
WHERE POSITION_NAME = 'Magazynier'
ORDER BY BIRTH_DATE DESC
LIMIT 5;

SELECT CLIENT.SHORT_NAME AS klient_1, KLIENT1.SHORT_NAME AS klient_2
FROM CLIENT
JOIN CLIENT AS KLIENT1
ON KLIENT1.CLIENT_ID = CLIENT.CLIENT_ID + 5;


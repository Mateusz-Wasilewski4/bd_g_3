SELECT AVG(pensja) AS srednia_pensja, POSITION_NAME AS stanowisko
FROM EMPLOYEE
NATURAL JOIN JOB_POSITION
NATURAL JOIN DEPARTMENT
WHERE DEPARTMENT_NAME NOT IN ('IT', 'HR')
GROUP BY JOB_POSITION_ID, POSITION_NAME
HAVING COUNT(*) > 3;

